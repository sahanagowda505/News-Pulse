def find_spark_submit() -> str:
    """Locate spark-submit binary in standard paths or PATH."""
    candidates = [
        "/usr/local/bin/spark-submit",
        os.environ.get("SPARK_HOME", "") + "/bin/spark-submit",
        "/opt/spark/bin/spark-submit",
        "/usr/local/spark/bin/spark-submit",
        "spark-submit",
    ]
    for cand in candidates:
        if cand == "spark-submit" or os.path.isfile(cand):
            return cand
    return "spark-submit"


def run_scala_spark_job(input_csv: Path, z_threshold: float = 1.8) -> tuple[bool, str]:
    """Execute the compiled Scala Apache Spark pipeline via spark-submit."""
    if not SPARK_JAR.exists():
        return False, f"Compiled Spark JAR not found at {SPARK_JAR}. Build it first using scripts/build_spark.sh."

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    cmd = [
        find_spark_submit(),
        "--master",
        "local[*]",
        "--driver-memory",
        "1g",
        "--class",
        "com.newspulse.NewsPulseJob",
        str(SPARK_JAR),
        str(input_csv),
        str(OUTPUT_DIR),
        str(z_threshold),
    ]
    env = os.environ.copy()
    env.setdefault("SPARK_HOME", "/opt/spark")
    env.setdefault("SPARK_LOCAL_IP", "127.0.0.1")
    proc = subprocess.run(cmd, capture_output=True, text=True, cwd=str(ROOT_DIR), env=env)
    if proc.returncode != 0:
        err_msg = proc.stderr.strip() or proc.stdout.strip() or "Unknown Spark execution error."
        for line in err_msg.splitlines():
            if "VALIDATION_ERROR:" in line or "PIPELINE_ERROR:" in line:
                return False, line.split(":", 1)[1].strip()
        return False, err_msg[-800:]
    return True, proc.stdout.strip()


def load_csv_dir_rows(folder_name: str) -> list[dict]:
    """Read Spark-generated CSV output folder (part-*.csv) without using Pandas."""
    import csv

    target_dir = OUTPUT_DIR / "csv" / folder_name
    part_files = sorted(glob.glob(str(target_dir / "part-*.csv")))
    if not part_files:
        return []
    rows = []
    for path in part_files:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            reader = csv.DictReader(f)
            for row in reader:
                rows.append(row)
    return rows


def load_parquet_count(folder_name: str) -> int:
    """Verify and read row count directly from Spark Parquet output."""
    target_dir = OUTPUT_DIR / "parquet" / folder_name
    part_files = sorted(glob.glob(str(target_dir / "*.parquet")))
    if not part_files:
        return 0
    table = pq.read_table(target_dir)
    return table.num_rows


def load_summary() -> dict | None:
    summary_path = OUTPUT_DIR / "pipeline_summary.json"
    if not summary_path.exists():
        return None
    with open(summary_path, "r", encoding="utf-8") as f:
        return json.load(f)


def build_parquet_zip() -> bytes:
    """Package Spark Parquet output directory into a downloadable ZIP archive."""
    buf = io.BytesIO()
    parquet_root = OUTPUT_DIR / "parquet"
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in parquet_root.rglob("*"):
            if path.is_file() and not path.name.startswith(".") and not path.name.endswith(".crc"):
                zf.write(path, arcname=path.relative_to(OUTPUT_DIR))
    return buf.getvalue()


